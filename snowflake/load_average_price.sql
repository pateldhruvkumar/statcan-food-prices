USE SCHEMA STATSCAN_ANALYTICS.SOURCE;

-- 1. Stage: points to the S3 folder
CREATE STAGE IF NOT EXISTS STATSCAN_S3_STAGE
  URL = 's3://stats-canada-grocery-data/landing/'
  STORAGE_INTEGRATION = STATSCAN_S3_INT;

-- 2. File format: CSV with a header row
CREATE FILE FORMAT IF NOT EXISTS STATSCAN_CSV
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"';

-- 3. Table: columns are taken from the CSV header
CREATE TABLE IF NOT EXISTS SOURCE_AVERAGE_PRICE
  USING TEMPLATE (
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*))
    FROM TABLE(INFER_SCHEMA(
      LOCATION => '@STATSCAN_S3_STAGE/average-price/',
      FILE_FORMAT => 'STATSCAN_CSV')));

-- 4. Load the data
COPY INTO SOURCE_AVERAGE_PRICE
  FROM @STATSCAN_S3_STAGE/average-price/
  FILE_FORMAT = (FORMAT_NAME = 'STATSCAN_CSV')
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
